// Writes apps/web/pages/upstream.gen.ts (gitignored): the Supabase function URL the /api proxy forwards to.
// CLI: node scripts/render-pages.mjs <out> <ref>
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export function renderUpstream(ref) {
  if (!/^[a-z0-9]{10,30}$/.test(ref ?? "")) throw new Error("SUPABASE_PROJECT_REF must be a 10-30 char lowercase id");
  return `// Generated by scripts/render-pages.mjs. Do not edit.\nexport const UPSTREAM = "https://${ref}.supabase.co/functions/v1/meally";\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const [out, ref] = process.argv.slice(2);
  fs.writeFileSync(out, renderUpstream(ref));
}
